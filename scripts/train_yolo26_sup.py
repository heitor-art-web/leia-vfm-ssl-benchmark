#!/usr/bin/env python3
"""Run one supervised YOLO26-sem baseline from an explicit dataset view.

A low-label benchmark must never accidentally train on every mask in the frozen
training export. This runner therefore requires a run-specific data YAML whose
`train` entry is a `*.txt` image list (normally generated by
`scripts/make_lidc_dataset_view.py`).

The script has a `--dry-run` path so the resolved training arguments can be
inspected before installing/running Ultralytics.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--config",
        type=Path,
        default=Path("configs/lidc_benchmark.yaml"),
    )
    parser.add_argument(
        "--data",
        type=Path,
        required=True,
        help="Run-specific semantic dataset YAML; train must point to a labelled-image .txt list.",
    )
    parser.add_argument(
        "--model-scale",
        choices=("smoke", "benchmark"),
        default="smoke",
        help="Use n-sem for smoke tests or the pre-declared s-sem core checkpoint.",
    )
    parser.add_argument("--seed", type=int, default=None)
    parser.add_argument("--device", default=None)
    parser.add_argument("--project", default="runs/lidc_sup")
    parser.add_argument("--name", default=None)
    parser.add_argument("--dry-run", action="store_true")
    return parser.parse_args()


def validate_dataset_view(data_yaml: Path, *, require_files: bool) -> dict:
    if not data_yaml.exists():
        if require_files:
            raise FileNotFoundError(data_yaml)
        return {}

    with data_yaml.open("r", encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    if not isinstance(data, dict):
        raise ValueError("dataset YAML must contain a mapping")
    if data.get("masks_dir") != "masks":
        raise ValueError("semantic dataset view must set masks_dir: masks")

    train = data.get("train")
    if not isinstance(train, str) or Path(train).suffix.lower() != ".txt":
        raise ValueError(
            "supervised benchmark data YAML must use a .txt train image list; "
            "directory-wide training is refused to prevent label-budget leakage"
        )

    if require_files:
        train_list = Path(train)
        if not train_list.is_absolute():
            # Ultralytics may resolve paths relative to `path`; the generated
            # benchmark views use absolute list paths, so reject ambiguity here.
            raise ValueError("benchmark train image-list path must be absolute")
        if not train_list.exists():
            raise FileNotFoundError(train_list)
        entries = [line.strip() for line in train_list.read_text(encoding="utf-8").splitlines() if line.strip()]
        if not entries:
            raise ValueError("train image list is empty")

    return data


def resolve_training_config(config: dict, args: argparse.Namespace) -> dict:
    model = config["model"]
    training = config["training"]
    augmentation = training.get("augmentation", {})

    checkpoint_key = (
        "smoke_checkpoint" if args.model_scale == "smoke" else "benchmark_checkpoint"
    )
    checkpoint = model[checkpoint_key]
    seed = int(args.seed if args.seed is not None else config["seed"])

    run_name = args.name or f"sup_{args.model_scale}_seed{seed}"
    resolved = {
        "checkpoint": checkpoint,
        "data": str(args.data),
        "epochs": int(training["epochs"]),
        "imgsz": int(training["image_size"]),
        "batch": int(training["batch_size"]),
        "optimizer": str(training["optimizer"]),
        "lr0": float(training["learning_rate"]),
        "weight_decay": float(training["weight_decay"]),
        "patience": int(training["early_stopping_patience"]),
        "seed": seed,
        "deterministic": bool(training["deterministic"]),
        "pretrained": bool(training["pretrained"]),
        "project": args.project,
        "name": run_name,
    }

    allowed_aug = {
        "hsv_h",
        "hsv_s",
        "hsv_v",
        "mosaic",
        "mixup",
        "copy_paste",
        "fliplr",
        "flipud",
        "degrees",
        "translate",
        "scale",
        "shear",
        "perspective",
    }
    unknown_aug = set(augmentation) - allowed_aug
    if unknown_aug:
        raise ValueError(f"unsupported augmentation keys: {sorted(unknown_aug)}")
    resolved.update({key: augmentation[key] for key in allowed_aug if key in augmentation})

    if args.device is not None:
        resolved["device"] = args.device
    return resolved


def main() -> None:
    args = parse_args()
    with args.config.open("r", encoding="utf-8") as handle:
        config = yaml.safe_load(handle)

    # Validate structure during dry-run when the view exists; require the files
    # for real training.
    validate_dataset_view(args.data, require_files=not args.dry_run)

    resolved = resolve_training_config(config, args)
    print(json.dumps(resolved, indent=2, sort_keys=True))

    if args.dry_run:
        return

    try:
        import torch
        import ultralytics
        from ultralytics import YOLO
    except ImportError as exc:
        raise SystemExit(
            "Missing YOLO26 runtime. Install with: pip install -r requirements-yolo26.txt"
        ) from exc

    print(f"ultralytics={ultralytics.__version__}")
    print(f"torch={torch.__version__}")

    model = YOLO(resolved.pop("checkpoint"))
    model.train(**resolved)


if __name__ == "__main__":
    main()
